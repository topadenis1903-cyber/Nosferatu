export function pickReply(chatId: string, text: string) {
  const bank = BANKS[chatId] ?? GENERIC;
  const hit = bank.rules.find((rule) => rule.test.test(text));
  const pool = hit?.replies ?? bank.any;
  return pool[Math.floor(Math.random() * pool.length)] ?? "Ок.";
}
